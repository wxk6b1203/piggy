/**
 * 从 pi 源码生成内置扩展表（`src-tauri/src/plugin/builtins_generated.rs`）。
 *
 * 为什么要有这个脚本：pi 的内置扩展是**源码里的常量**
 * （`packages/coding-agent/src/extensions/index.ts` 的 `builtInExtensions`），
 * 没有任何命令能列出来——RPC 没有扩展管理命令，`pi list` 只列 settings 里的包。
 * 而它确实"在运行"，所以插件页必须把它显示出来，否则用户会以为列表是全集。
 *
 * ⚠️ **1.1.0 起它的语义变了**（0.87 时代写死"不可增删、-ne 也关不掉"）：
 *   · 内置扩展现在是**合成路径** `builtin:<name>`，走普通资源解析
 *     （`resource-loader.ts` 的 `BUILTIN_PATH_PREFIX`），所以 settings 的
 *     `extensions[]` 里 `-builtin:<name>` 能**单独关掉**它（真机核对：mcp / llama 各一遍）；
 *   · `--no-extensions` 也真的能关掉（`this.noExtensions ? cliEnabledExtensions : …`）；
 *   · `replaceable: true` 的三个（codemode / tool-search / mcp）可以被别的扩展顶替。
 * 界面上的说明与"能不能停用"必须跟着这三条走，别再照抄 0.87 的说法。
 *
 * 用法：
 *   node scripts/gen-plugin-builtins.mjs <pi 源码根>           # 写文件
 *   node scripts/gen-plugin-builtins.mjs <pi 源码根> --check    # 只比对
 * 例：node apps/desktop/scripts/gen-plugin-builtins.mjs /Users/wxk/Documents/Project/pi
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src-tauri/src/plugin/builtins_generated.rs');

const piRoot = process.argv[2];
const checkOnly = process.argv.includes('--check');
if (!piRoot) {
  console.error('用法: node scripts/gen-plugin-builtins.mjs <pi 源码根> [--check]');
  process.exit(2);
}
const SRC = join(piRoot, 'packages/coding-agent/src/extensions/index.ts');
if (!existsSync(SRC)) {
  console.error(`找不到 ${SRC}——参数要指向 pi 仓库根目录`);
  process.exit(2);
}

const text = readFileSync(SRC, 'utf8');
const body = /export const builtInExtensions[^=]*=\s*\[([\s\S]*?)\];/.exec(text)?.[1];
if (body === undefined) {
  console.error('解析 builtInExtensions 失败——pi 可能改了形状，请人工核对');
  process.exit(1);
}

/* inline factory 一律被标成 hidden（`resource-loader.ts`：`extension.hidden = true;`
   就在 loadExtensionFactories 之后那一支里，1.1.0 实测）。源码里的 `hidden: true`
   只是 0.87 时代的写法，所以这里以**加载器的行为**为准，并把它抄进生成物头部，
   免得下次有人照着源码字面量又改回 false。 */
const loaderSrc = readFileSync(
  join(piRoot, 'packages/coding-agent/src/core/resource-loader.ts'),
  'utf8',
);
const inlineForcesHidden = /extension\.hidden\s*=\s*true/.test(loaderSrc);

// 只取字面量字段。`factory` 是标识符引用，脚本不去追它的实现，
// 因为界面只需要"叫什么、隐不隐藏、能不能被顶替"。
const entries = [...body.matchAll(/\{([^}]*)\}/g)].map((m) => {
  const fields = m[1];
  const name = /name:\s*"([^"]+)"/.exec(fields)?.[1];
  const hidden = inlineForcesHidden || /hidden:\s*true/.test(fields);
  const replaceable = /replaceable:\s*true/.test(fields);
  if (name === undefined) throw new Error(`无法从 ${m[0]} 解析 name`);
  // 入口目录：name 到目录名的映射没有通用规则，只有 llama.cpp → llama 这一条实测事实。
  // 与其猜，不如把声明所在的文件路径记下来，界面显示"随 pi 发布"。
  return { name, hidden, replaceable };
});
if (entries.length === 0) throw new Error('builtInExtensions 解析出 0 条');

const piVersion = JSON.parse(
  readFileSync(join(piRoot, 'packages/coding-agent/package.json'), 'utf8'),
).version;
let piCommit = '';
try {
  piCommit = execFileSync('git', ['-C', piRoot, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  /* 不是 git 仓库就算了，头部注释而已 */
}

const rs = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const rows = entries
  .map(
    (e) =>
      `    Builtin { name: ${rs(e.name)}, hidden: ${e.hidden}, replaceable: ${e.replaceable}, path: ${rs(
        `(pi 内置：packages/coding-agent/src/extensions/${e.name === 'llama.cpp' ? 'llama' : e.name})`,
      )} },`,
  )
  .join('\n');

const out = `// @generated by apps/desktop/scripts/gen-plugin-builtins.mjs —— 请勿手改，改脚本后重跑。
//
// 数据来源：pi v${piVersion}（git ${piCommit}）
//   packages/coding-agent/src/extensions/index.ts   builtInExtensions
//
// pi 的内置扩展没有运行时枚举接口（RPC 无扩展命令、\`pi list\` 只列 settings 的包），
// 所以只能在编译期固化。**随 pi 版本漂移**：升级 pi 后重跑本脚本（--check 可用于 CI）。
//
// 重新生成：node apps/desktop/scripts/gen-plugin-builtins.mjs <pi 源码根>

/// pi 的内置扩展。
///
/// 三个字段都是"界面该怎么说"的依据，不是装饰：
/// - \`hidden\`：pi 自己在启动横幅里也不显示它（inline factory 一律 \`extension.hidden = true\`，
///   \`resource-loader.ts\` 的 loadExtensionFactories 之后那一支）；
/// - \`replaceable\`：可以被别的扩展**顶替**（pi 1.1.0 的 \`omitReplacedExtensions\`）。
///   codemode / tool-search / mcp 是 true；llama.cpp 是 false；
/// - \`path\`：合成路径的说明文字（\`builtin:<name>\` 才是它真正的"路径"）。
///
/// ⚠️ 1.1.0 起它们**可以停用**（settings 的 \`extensions[]\` 写 \`-builtin:<name>\`，
/// 或整进程 \`--no-extensions\`）—— 0.87 时代"不可增删、-ne 也关不掉"的说法已过期。
pub struct Builtin {
    pub name: &'static str,
    pub hidden: bool,
    pub replaceable: bool,
    pub path: &'static str,
}

/// pi ${piVersion} 的 ${entries.length} 个内置扩展。
#[rustfmt::skip]
pub const BUILTINS: &[Builtin] = &[
${rows}
];
`;

if (checkOnly) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  const dataLines = (s) => s.split('\n').filter((l) => l.trimStart().startsWith('Builtin {')).join('\n');
  if (dataLines(current) !== dataLines(out)) {
    console.error('❌ 内置扩展表与 pi 源码不一致（--check）');
    process.exit(1);
  }
  console.log(`✅ 内置扩展表一致（${entries.length} 条）`);
} else {
  writeFileSync(OUT, out);
  console.log(`已写出 ${OUT}（${entries.length} 条：${entries.map((e) => e.name).join(', ')}）`);
}
