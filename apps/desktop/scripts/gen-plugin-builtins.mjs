/**
 * 从 pi 源码生成内置扩展表（`src-tauri/src/plugin/builtins_generated.rs`）。
 *
 * 为什么要有这个脚本：pi 的内置扩展是**源码里的常量**
 * （`packages/coding-agent/src/extensions/index.ts` 的 `builtInExtensions`），
 * 没有任何命令能列出来——RPC 的 33 条命令里一条都不沾扩展管理，`pi list` 只列
 * settings 里的包。而它又确实"在运行"（`resource-loader.ts:559-567` 无条件加载
 * inline factory，连 `-ne` 都关不掉），所以插件页必须把它显示出来并明确标注
 * **不可卸载**，否则用户会以为列表是全集。
 *
 * 用法：
 *   node scripts/gen-plugin-builtins.mjs <pi 源码根>           # 写文件
 *   node scripts/gen-plugin-builtins.mjs <pi 源码根> --check    # 只比对
 * 例：node apps/desktop/scripts/gen-plugin-builtins.mjs /Users/wxk/Documents/Project/pi
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(here, '../src-tauri/src/plugin/builtins_generated.rs');

const piRoot = process.argv[2];
const checkOnly = process.argv.includes('--check');
if (!piRoot) {
  console.error('用法: node scripts/gen-plugin-builtins.mjs <pi 源码根> [--check]');
  process.exit(2);
}
const SRC = join(piRoot, 'packages/coding-agent/src/extensions/index.ts');
if (!existsSync(SRC)) {
  console.error(`找不到 ${SRC}——参数要指向 pi 仓库根目录`);
  process.exit(2);
}

const text = readFileSync(SRC, 'utf8');
const body = /export const builtInExtensions[^=]*=\s*\[([\s\S]*?)\];/.exec(text)?.[1];
if (body === undefined) {
  console.error('解析 builtInExtensions 失败——pi 可能改了形状，请人工核对');
  process.exit(1);
}

// 只取字面量字段。`factory` 是标识符引用，脚本不去追它的实现，
// 因为界面只需要"叫什么、隐不隐藏"。
const entries = [...body.matchAll(/\{([^}]*)\}/g)].map((m) => {
  const fields = m[1];
  const name = /name:\s*"([^"]+)"/.exec(fields)?.[1];
  const hidden = /hidden:\s*true/.test(fields);
  if (name === undefined) throw new Error(`无法从 ${m[0]} 解析 name`);
  // 入口目录：name 到目录名的映射没有通用规则，只有 llama.cpp → llama 这一条实测事实。
  // 与其猜，不如把声明所在的文件路径记下来，界面显示"随 pi 发布"。
  return { name, hidden };
});
if (entries.length === 0) throw new Error('builtInExtensions 解析出 0 条');

const piVersion = JSON.parse(
  readFileSync(join(piRoot, 'packages/coding-agent/package.json'), 'utf8'),
).version;
let piCommit = '';
try {
  piCommit = execFileSync('git', ['-C', piRoot, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim();
} catch {
  /* 不是 git 仓库就算了，头部注释而已 */
}

const rs = (s) => `"${s.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
const rows = entries
  .map(
    (e) =>
      `    Builtin { name: ${rs(e.name)}, hidden: ${e.hidden}, path: ${rs(
        `(pi 内置：packages/coding-agent/src/extensions/${e.name === 'llama.cpp' ? 'llama' : e.name})`,
      )} },`,
  )
  .join('\n');

const out = `// @generated by apps/desktop/scripts/gen-plugin-builtins.mjs —— 请勿手改，改脚本后重跑。
//
// 数据来源：pi v${piVersion}（git ${piCommit}）
//   packages/coding-agent/src/extensions/index.ts   builtInExtensions
//
// pi 的内置扩展没有运行时枚举接口（RPC 无扩展命令、\`pi list\` 只列 settings 的包），
// 所以只能在编译期固化。**随 pi 版本漂移**：升级 pi 后重跑本脚本（--check 可用于 CI）。
//
// 重新生成：node apps/desktop/scripts/gen-plugin-builtins.mjs <pi 源码根>

/// pi 的内置扩展（inline factory）。
///
/// \`hidden\` = pi 自己在启动横幅里也不显示它（\`interactive-mode.ts:1741\`）；
/// 对用户而言它**既不能卸载也不能停用**——\`--no-extensions\` 也拦不住 inline factory
/// （\`resource-loader.ts:559-567\`）。界面必须如实标注。
pub struct Builtin {
    pub name: &'static str,
    pub hidden: bool,
    pub path: &'static str,
}

/// pi ${piVersion} 的 ${entries.length} 个内置扩展。
pub const BUILTINS: &[Builtin] = &[
${rows}
];
`;

if (checkOnly) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  const dataLines = (s) => s.split('\n').filter((l) => l.trimStart().startsWith('Builtin {')).join('\n');
  if (dataLines(current) !== dataLines(out)) {
    console.error('❌ 内置扩展表与 pi 源码不一致（--check）');
    process.exit(1);
  }
  console.log(`✅ 内置扩展表一致（${entries.length} 条）`);
} else {
  writeFileSync(OUT, out);
  console.log(`已写出 ${OUT}（${entries.length} 条：${entries.map((e) => e.name).join(', ')}）`);
}
